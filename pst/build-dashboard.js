#!/usr/bin/env node
/* build-dashboard.js — scan the PST units and emit dashboard-data.js (window.PST_DASHBOARD),
   which powers dashboard.html: counts of surface/deep/transfer activities, the high-effect
   strategies used (from each activity's .es tag), a per-grade breakdown, and entry/exit
   arcade-ticket counts (from games/, 0 until that ships).
   Run:  node pst/build-dashboard.js */
const fs = require('fs'), path = require('path'), cp = require('child_process');
const ROOT = __dirname;
// each band = a folder holding unit subfolders, plus a display label for the "By band" table
const BANDS = [
  { dir: 'grade3', label: 'Grade 3' }, { dir: 'grade4', label: 'Grade 4' },
  { dir: 'grade5', label: 'Grade 5' }, { dir: 'grade6', label: 'Grade 6' },
  { dir: 'grade7', label: 'Grade 7' }, { dir: 'grade8', label: 'Grade 8' },
  { dir: 'hs-us-history', label: 'HS · US History' },
];
const PHASES = ['surface', 'deep', 'transfer'];
const decode = s => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#39;|&rsquo;/g, "'");

const phases = { surface: 0, deep: 0, transfer: 0 };
const strategies = {};            // name -> { count, d }
const grades = {};                // gradeN -> { units, surface, deep, transfer }
let unitCount = 0;

for (const band of BANDS) {
  const g = band.dir;
  const gdir = path.join(ROOT, g);
  if (!fs.existsSync(gdir)) continue;
  grades[g] = { label: band.label, units: 0, surface: 0, deep: 0, transfer: 0 };
  for (const entry of fs.readdirSync(gdir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;                       // each unit is a subfolder
    const udir = path.join(gdir, entry.name);
    if (!fs.existsSync(path.join(udir, 'surface.html'))) continue;  // real units have phase pages
    grades[g].units++; unitCount++;
    for (const ph of PHASES) {
      const fp = path.join(udir, ph + '.html');
      if (!fs.existsSync(fp)) continue;
      const html = fs.readFileSync(fp, 'utf8');
      // activities in this phase = number of `.act <phase>` blocks
      const acts = (html.match(new RegExp('class="act ' + ph + '"', 'g')) || []).length;
      phases[ph] += acts; grades[g][ph] += acts;
      // strategies used = each activity's .es tag ("Name · d 0.xx")
      for (const m of html.matchAll(/<span class="es">([^<]+)<\/span>/g)) {
        const raw = decode(m[1]).trim();
        const mm = raw.match(/^(.*?)\s*·\s*d\s*([0-9.]+)/i);
        const name = (mm ? mm[1] : raw).trim();
        const d = mm ? parseFloat(mm[2]) : null;
        if (!strategies[name]) strategies[name] = { count: 0, d };
        strategies[name].count++;
        if (d != null) strategies[name].d = d;
      }
    }
  }
}

// entry/exit arcade tickets — counted from the ticket registry (games/tickets.js)
const tickets = { entry: 0, exit: 0 };
const ticketsFile = path.join(ROOT, 'games', 'tickets.js');
if (fs.existsSync(ticketsFile)) {
  try {
    const sandbox = { window: {} };
    // tickets.js does `window.PST_TICKETS = (window.PST_TICKETS||[]).concat([...])`
    new Function('window', fs.readFileSync(ticketsFile, 'utf8'))(sandbox.window);
    (sandbox.window.PST_TICKETS || []).forEach(t => {
      if (t.type === 'entry') tickets.entry++;
      else if (t.type === 'exit') tickets.exit++;
    });
  } catch (_) {}
}

const strat = Object.entries(strategies)
  .map(([name, v]) => ({ name, d: v.d, count: v.count }))
  .sort((a, b) => b.count - a.count || (b.d || 0) - (a.d || 0));

const data = {
  generated: cp.execSync('git log -1 --format=%cI 2>/dev/null || true').toString().trim() || '',
  units: unitCount,
  phases: { ...phases, total: phases.surface + phases.deep + phases.transfer },
  strategies: strat,
  grades,
  tickets: { ...tickets, total: tickets.entry + tickets.exit },
};

fs.writeFileSync(path.join(ROOT, 'dashboard-data.js'),
  '/* Auto-generated by build-dashboard.js — do not edit by hand. */\n' +
  'window.PST_DASHBOARD = ' + JSON.stringify(data) + ';\n');
console.log(`dashboard-data.js: ${data.units} units · ${data.phases.total} activities ` +
  `(S ${phases.surface} / D ${phases.deep} / T ${phases.transfer}) · ${strat.length} strategies · ` +
  `${data.tickets.total} tickets`);
